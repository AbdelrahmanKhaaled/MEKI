#!/usr/bin/env node
// Phase 13A — creates deploy/staging/.env.staging (git-ignored) with fresh random secrets for a LOCAL staging rehearsal.
// Never prints a secret. Refuses to overwrite an existing file (rotating secrets is a deliberate operator action).
// Hosted staging: put the same keys in the hosting secret store instead of a file.
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const file = join(dirname(fileURLToPath(import.meta.url)), '.env.staging');
if (existsSync(file)) {
  console.log('deploy/staging/.env.staging already exists — left unchanged.');
  process.exit(0);
}
const secret = (bytes) => randomBytes(bytes).toString('base64url');
const lines = [
  '# Generated by deploy/staging/init-secrets.mjs — LOCAL staging rehearsal only. Never commit. Never reuse in production.',
  `MYSQL_ROOT_PASSWORD=${secret(24)}`,
  `MEKI_MIGRATOR_PASSWORD=${secret(24)}`,
  `MEKI_APP_DB_PASSWORD=${secret(24)}`,
  `EVENT_BOOKING_TOKEN_SECRET=${secret(48)}`,
  `DONATION_TOKEN_SECRET=${secret(48)}`,
  '# Local rehearsal origins (plain http on this machine). Hosted staging: https origins and STAGING_LOCAL_REHEARSAL=false.',
  'STAGING_WEB_URL=http://localhost:3200',
  'STAGING_ADMIN_URL=http://localhost:3201',
  'STAGING_API_URL=http://localhost:4200',
  'STAGING_LOCAL_REHEARSAL=true',
  'TRUST_PROXY=1',
  '',
];
writeFileSync(file, lines.join('\n'), { mode: 0o600 });
console.log('deploy/staging/.env.staging created (secrets generated, not displayed).');
