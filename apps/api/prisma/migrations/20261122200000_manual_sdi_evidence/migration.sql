-- Additive private evidence queue; no existing financial records are rewritten.
CREATE TABLE `ManualPaymentEvidence` (
    `id` VARCHAR(30) NOT NULL,
    `targetType` VARCHAR(20) NOT NULL,
    `targetId` VARCHAR(30) NOT NULL,
    `reference` VARCHAR(24) NOT NULL,
    `evidenceReference` VARCHAR(24) NULL,
    `externalPaymentId` VARCHAR(64) NULL,
    `amount` DECIMAL(18, 2) NULL,
    `currency` CHAR(3) NULL,
    `occurredAt` DATETIME(3) NULL,
    `formUrl` VARCHAR(1000) NULL,
    `classification` VARCHAR(10) NULL,
    `emailMessageId` VARCHAR(255) NULL,
    `emailFrom` VARCHAR(191) NULL,
    `emailTo` VARCHAR(191) NULL,
    `emailReceivedAt` DATETIME(3) NULL,
    `protectedReference` VARCHAR(255) NULL,
    `originalSdiEmail` BOOLEAN NOT NULL DEFAULT false,
    `note` VARCHAR(500) NOT NULL,
    `status` VARCHAR(30) NOT NULL DEFAULT 'PENDING_REVIEW',
    `reviewReason` VARCHAR(500) NULL,
    `submittedById` VARCHAR(30) NOT NULL,
    `decidedById` VARCHAR(30) NULL,
    `decidedAt` DATETIME(3) NULL,
    `decisionNote` VARCHAR(500) NULL,
    `reportReconciledAt` DATETIME(3) NULL,
    `reportImportId` VARCHAR(30) NULL,
    `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),

    INDEX `ManualPaymentEvidence_status_createdAt_idx`(`status`, `createdAt`),
    INDEX `ManualPaymentEvidence_targetType_targetId_idx`(`targetType`, `targetId`),
    INDEX `ManualPaymentEvidence_externalPaymentId_idx`(`externalPaymentId`),
    PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
