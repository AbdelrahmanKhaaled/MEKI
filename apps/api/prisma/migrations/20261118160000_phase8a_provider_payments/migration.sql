CREATE TABLE `ProviderPayment` (
    `id` VARCHAR(30) NOT NULL,
    `provider` VARCHAR(40) NOT NULL,
    `providerPaymentId` VARCHAR(64) NOT NULL,
    `status` VARCHAR(40) NOT NULL,
    `type` VARCHAR(20) NOT NULL,
    `amount` DECIMAL(18, 2) NOT NULL,
    `eligibleAmount` DECIMAL(18, 2) NOT NULL,
    `refundedAmount` DECIMAL(18, 2) NOT NULL DEFAULT 0,
    `refundStatus` VARCHAR(20) NOT NULL,
    `disputeStatus` VARCHAR(30) NULL,
    `currency` CHAR(3) NOT NULL,
    `campaignId` VARCHAR(64) NULL,
    `campaignCategory` VARCHAR(30) NULL,
    `occurrenceId` VARCHAR(64) NULL,
    `recurringSubscriptionId` VARCHAR(64) NULL,
    `recurringInterval` VARCHAR(20) NULL,
    `classification` ENUM('CHARITABLE_DONATION', 'EVENT_TICKET_PAYMENT') NULL,
    `items` JSON NOT NULL,
    `correlationRef` VARCHAR(40) NULL,
    `matchStatus` ENUM('UNMATCHED', 'NEEDS_REVIEW', 'MATCHED', 'CONFIRMED', 'IGNORED') NOT NULL DEFAULT 'UNMATCHED',
    `matchReason` VARCHAR(200) NULL,
    `matchedEntityType` VARCHAR(40) NULL,
    `matchedEntityId` VARCHAR(30) NULL,
    `providerCreatedAt` DATETIME(3) NOT NULL,
    `deletedAtProvider` DATETIME(3) NULL,
    `lastEventId` VARCHAR(80) NULL,
    `lastSyncedAt` DATETIME(3) NOT NULL,
    `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `updatedAt` DATETIME(3) NOT NULL,

    INDEX `ProviderPayment_matchStatus_idx`(`matchStatus`),
    INDEX `ProviderPayment_campaignId_idx`(`campaignId`),
    INDEX `ProviderPayment_providerCreatedAt_idx`(`providerCreatedAt`),
    UNIQUE INDEX `ProviderPayment_provider_providerPaymentId_key`(`provider`, `providerPaymentId`),
    UNIQUE INDEX `ProviderPayment_provider_matchedEntityType_matchedEntityId_key`(`provider`, `matchedEntityType`, `matchedEntityId`),
    PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
