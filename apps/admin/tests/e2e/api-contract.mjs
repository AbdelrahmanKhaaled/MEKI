import { AuthUserSchema, ByCampaignSchema, ByDateSchema, CampaignRowSchema, CheckInStatsSchema, DonationRowSchema, EventRowSchema, GalaConfigSchema, GalaFinancialsSchema, AuditRowSchema, SummarySchema, LoginSchema, CsrfSchema } from "../../src/lib/schemas.ts";
// Validates the admin response schemas against a RUNNING API (never run against production). Usage: node tests/e2e/api-contract.mjs <admin-email> [password] — API at API_URL (default http://localhost:4000)
const API = `${process.env.API_URL ?? "http://localhost:4000"}/api/v1`;
let cookie = "";
const call = async (path, init = {}) => {
  const r = await fetch(API + path, { ...init, headers: { "Content-Type": "application/json", Cookie: cookie, ...(init.headers ?? {}) } });
  const sc = r.headers.getSetCookie?.() ?? [];
  if (sc.length) cookie = sc.map((c) => c.split(";")[0]).join("; ");
  return { status: r.status, json: await r.json().catch(() => null) };
};
const login = await call("/admin/auth/login", { method: "POST", body: JSON.stringify({ email: process.argv[2], password: process.argv[3] ?? "Test-Password-2026!" }) });
const ok = (name, schema, data) => { const p = schema.safeParse(data); console.log(p.success ? "OK  " : "FAIL", name, p.success ? "" : JSON.stringify(p.error.issues.slice(0, 3))); };
ok("login", LoginSchema, login.json?.data);
ok("me", AuthUserSchema, (await call("/admin/auth/me")).json?.data);
ok("csrf", CsrfSchema, (await call("/admin/auth/csrf")).json?.data);
const q = "?includeTest=true";
ok("summary", SummarySchema, (await call("/admin/reports/donations/summary" + q)).json?.data);
ok("by-date", ByDateSchema, (await call("/admin/reports/donations/by-date" + q)).json?.data);
ok("by-campaign", ByCampaignSchema, (await call("/admin/reports/donations/by-campaign" + q)).json?.data);
const don = (await call("/admin/donations" + q + "&pageSize=20")).json;
console.log("donations items:", don.data.length, "meta", JSON.stringify(don.meta));
ok("donations[]", DonationRowSchema.array(), don.data);
const camp = (await call("/admin/campaigns?pageSize=50")).json;
console.log("campaign items:", camp.data.length);
ok("campaigns[]", CampaignRowSchema.array(), camp.data);
const aud = (await call("/admin/audit-logs?pageSize=6")).json;
ok("audit[]", AuditRowSchema.array(), aud.data);
const ev = (await call("/admin/events?search=EVT-GALA-NIGHT&pageSize=5")).json;
ok("events[]", EventRowSchema.array(), ev.data);
const g = ev.data.find((e) => e.code === "EVT-GALA-NIGHT");
const fin = (await call(`/admin/events/${g.id}/financials?includeTest=true`)).json?.data;
ok("gala financials", GalaFinancialsSchema, fin);
ok("gala config", GalaConfigSchema, (await call(`/admin/events/${g.id}/ticketing`)).json?.data);
ok("check-in stats", CheckInStatsSchema, (await call(`/admin/events/${g.id}/check-in/statistics`)).json?.data);
const pc = await call("/admin/programmes?status=PUBLISHED&kind=PROGRAMME&page=1&pageSize=1");
console.log("programmes count meta:", JSON.stringify(pc.json?.meta));
const dc = await call("/admin/donors?page=1&pageSize=1");
console.log("donors count meta:", JSON.stringify(dc.json?.meta));
console.log("sample donation designation/allocs:", JSON.stringify(don.data[0]?.allocations ?? null).slice(0, 160));
